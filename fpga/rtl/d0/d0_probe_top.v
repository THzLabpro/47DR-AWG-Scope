`timescale 1ns/1ps

// D0 timing probe.  The RFDC/PS/SYSREF topology follows the published
// dac9g_mts top level; the data paths are deliberately small boundary stubs.
module d0_probe_top (
    input  pl_clk_n, input pl_clk_p,
    input  pl_sysref_n, input  pl_sysref_p,
    input  adc1_clk_n, input  adc1_clk_p,
    input  dac2_clk_n, input  dac2_clk_p,
    input  sysref_in_n, input  sysref_in_p,
    input  vin0_01_n, input  vin0_01_p,
    input  vin0_23_n, input  vin0_23_p,
    input  vin1_01_n, input  vin1_01_p,
    input  vin1_23_n, input  vin1_23_p,
    input  vin2_01_n, input  vin2_01_p,
    input  vin2_23_n, input  vin2_23_p,
    input  vin3_01_n, input  vin3_01_p,
    input  vin3_23_n, input  vin3_23_p,
    output vout00_n, output vout00_p,
    output vout02_n, output vout02_p,
    output vout10_n, output vout10_p,
    output vout12_n, output vout12_p,
    output vout20_n, output vout20_p,
    output vout22_n, output vout22_p,
    output vout30_n, output vout30_p,
    output vout32_n, output vout32_p,
    output [1:0] led
);

    wire pl_clk_raw;
    wire pl_clk;
    wire pl_sysref;
    IBUFDS pl_clk_ibufds (.I(pl_clk_p), .IB(pl_clk_n), .O(pl_clk_raw));
    BUFG pl_clk_bufg (.I(pl_clk_raw), .O(pl_clk));
    IBUFDS pl_sysref_ibufds (.I(pl_sysref_p), .IB(pl_sysref_n), .O(pl_sysref));

    reg pl_sysref_r;
    (* ASYNC_REG = "TRUE" *) reg sysref_adc_meta;
    (* ASYNC_REG = "TRUE" *) reg sysref_dac_meta;
    (* ASYNC_REG = "TRUE" *) reg user_sysref_adc;
    (* ASYNC_REG = "TRUE" *) reg user_sysref_dac;

    wire data_clk;
    wire adc_clk;
    wire tx_clk;
    wire rx_clk;
    wire fclk_100m;
    wire pl_resetn0;
    wire rf_resetn;
    wire host_resetn;
    wire adc_axis_resetn;

    wire dac_resetn_sync;
    wire tx_resetn_sync;
    wire adc_resetn_sync;
    wire rx_resetn_sync;
    wire host_resetn_sync;

    d0_reset_sync dac_reset_sync_i (
        .clk(data_clk), .async_resetn(rf_resetn), .resetn(dac_resetn_sync));
    d0_reset_sync tx_reset_sync_i (
        .clk(tx_clk), .async_resetn(rf_resetn), .resetn(tx_resetn_sync));
    d0_reset_sync adc_reset_sync_i (
        .clk(adc_clk), .async_resetn(adc_axis_resetn), .resetn(adc_resetn_sync));
    d0_reset_sync rx_reset_sync_i (
        .clk(rx_clk), .async_resetn(adc_axis_resetn), .resetn(rx_resetn_sync));
    d0_reset_sync host_reset_sync_i (
        .clk(fclk_100m), .async_resetn(host_resetn), .resetn(host_resetn_sync));

    always @(posedge pl_clk) begin
        pl_sysref_r <= pl_sysref;
    end
    always @(posedge adc_clk) begin
        sysref_adc_meta <= pl_sysref_r;
        user_sysref_adc <= sysref_adc_meta;
    end
    always @(posedge data_clk) begin
        sysref_dac_meta <= pl_sysref_r;
        user_sysref_dac <= sysref_dac_meta;
    end

    // Related clocks are generated by BUFGCE_DIV.  The XDC keeps these
    // clocks synchronous to their parent domains.
    BUFGCE_DIV #(.BUFGCE_DIVIDE(2)) tx_clk_div (
        .I(data_clk), .CE(1'b1), .CLR(1'b0), .O(tx_clk));
    BUFGCE_DIV #(.BUFGCE_DIVIDE(2)) rx_clk_div (
        .I(adc_clk), .CE(1'b1), .CLR(1'b0), .O(rx_clk));

    wire [8*256-1:0] dac_s_tdata;
    wire [7:0] dac_s_tvalid;
    wire [7:0] dac_s_tready;
    wire [191:0] adc_ch_tdata [0:7];
    wire adc_ch_valid [0:7];
    wire [7:0] adc_ch_ready = 8'hff;
    wire [8*32-1:0] rx_host_data;
    wire [8*336-1:0] rx_probe_data;

    genvar ch;
    generate
        for (ch = 0; ch < 8; ch = ch + 1) begin : g_channels
            (* MAX_FANOUT = 64 *) reg dac_resetn_local;
            (* MAX_FANOUT = 64 *) reg tx_resetn_local;
            (* MAX_FANOUT = 64 *) reg adc_resetn_local;
            (* MAX_FANOUT = 64 *) reg rx_resetn_local;
            (* MAX_FANOUT = 64 *) reg host_resetn_local;

            always @(posedge data_clk or negedge rf_resetn) begin
                if (!rf_resetn) dac_resetn_local <= 1'b0;
                else dac_resetn_local <= dac_resetn_sync;
            end
            always @(posedge tx_clk or negedge rf_resetn) begin
                if (!rf_resetn) tx_resetn_local <= 1'b0;
                else tx_resetn_local <= tx_resetn_sync;
            end
            always @(posedge adc_clk or negedge adc_axis_resetn) begin
                if (!adc_axis_resetn) adc_resetn_local <= 1'b0;
                else adc_resetn_local <= adc_resetn_sync;
            end
            always @(posedge rx_clk or negedge adc_axis_resetn) begin
                if (!adc_axis_resetn) rx_resetn_local <= 1'b0;
                else rx_resetn_local <= rx_resetn_sync;
            end
            always @(posedge fclk_100m or negedge host_resetn) begin
                if (!host_resetn) host_resetn_local <= 1'b0;
                else host_resetn_local <= host_resetn_sync;
            end

            d0_tx_stub #(.CHANNEL(ch)) tx_stub_i (
                .tx_clk(tx_clk), .dac_clk(data_clk),
                .tx_resetn(tx_resetn_local), .dac_resetn(dac_resetn_local),
                .dac_tdata(dac_s_tdata[ch*256 +: 256]),
                .dac_tvalid(dac_s_tvalid[ch]), .dac_tready(dac_s_tready[ch]));
            d0_rx_stub #(.CHANNEL(ch)) rx_stub_i (
                .adc_clk(adc_clk), .rx_clk(rx_clk), .host_clk(fclk_100m),
                .adc_resetn(adc_resetn_local), .rx_resetn(rx_resetn_local),
                .host_resetn(host_resetn_local),
                .adc_tdata(adc_ch_tdata[ch]),
                .adc_tvalid(adc_ch_valid[ch]),
                .host_data(rx_host_data[ch*32 +: 32]),
                .probe_data(rx_probe_data[ch*336 +: 336]));
        end
    endgenerate

    wire [255:0] s00_axis_tdata = dac_s_tdata[255:0];
    wire [255:0] s02_axis_tdata = dac_s_tdata[511:256];
    wire [255:0] s10_axis_tdata = dac_s_tdata[767:512];
    wire [255:0] s12_axis_tdata = dac_s_tdata[1023:768];
    wire [255:0] s20_axis_tdata = dac_s_tdata[1279:1024];
    wire [255:0] s22_axis_tdata = dac_s_tdata[1535:1280];
    wire [255:0] s30_axis_tdata = dac_s_tdata[1791:1536];
    wire [255:0] s32_axis_tdata = dac_s_tdata[2047:1792];
    wire s00_axis_tvalid = dac_s_tvalid[0];
    wire s02_axis_tvalid = dac_s_tvalid[1];
    wire s10_axis_tvalid = dac_s_tvalid[2];
    wire s12_axis_tvalid = dac_s_tvalid[3];
    wire s20_axis_tvalid = dac_s_tvalid[4];
    wire s22_axis_tvalid = dac_s_tvalid[5];
    wire s30_axis_tvalid = dac_s_tvalid[6];
    wire s32_axis_tvalid = dac_s_tvalid[7];

    wire up_rack;
    wire [15:0] up_raddr;
    wire [31:0] up_rdata = 32'd0;
    wire up_rreq;
    wire up_wack = 1'b0;
    wire [15:0] up_waddr;
    wire [31:0] up_wdata;
    wire up_wreq;

    system system_i (
        .adc1_clk_clk_n(adc1_clk_n), .adc1_clk_clk_p(adc1_clk_p),
        .dac2_clk_clk_n(dac2_clk_n), .dac2_clk_clk_p(dac2_clk_p),
        .data_clk(data_clk), .adc_capture_clk(adc_clk),
        .adc_axis_resetn(adc_axis_resetn), .pl_resetn0(pl_resetn0),
        .rf_resetn(rf_resetn), .host_resetn(host_resetn),
        .m00_axis_tdata(adc_ch_tdata[0]), .m00_axis_tready(adc_ch_ready[0]), .m00_axis_tvalid(adc_ch_valid[0]),
        .m02_axis_tdata(adc_ch_tdata[1]), .m02_axis_tready(adc_ch_ready[1]), .m02_axis_tvalid(adc_ch_valid[1]),
        .m10_axis_tdata(adc_ch_tdata[2]), .m10_axis_tready(adc_ch_ready[2]), .m10_axis_tvalid(adc_ch_valid[2]),
        .m12_axis_tdata(adc_ch_tdata[3]), .m12_axis_tready(adc_ch_ready[3]), .m12_axis_tvalid(adc_ch_valid[3]),
        .m20_axis_tdata(adc_ch_tdata[4]), .m20_axis_tready(adc_ch_ready[4]), .m20_axis_tvalid(adc_ch_valid[4]),
        .m22_axis_tdata(adc_ch_tdata[5]), .m22_axis_tready(adc_ch_ready[5]), .m22_axis_tvalid(adc_ch_valid[5]),
        .m30_axis_tdata(adc_ch_tdata[6]), .m30_axis_tready(adc_ch_ready[6]), .m30_axis_tvalid(adc_ch_valid[6]),
        .m32_axis_tdata(adc_ch_tdata[7]), .m32_axis_tready(adc_ch_ready[7]), .m32_axis_tvalid(adc_ch_valid[7]),
        .s00_axis_tdata(s00_axis_tdata), .s00_axis_tready(dac_s_tready[0]), .s00_axis_tvalid(s00_axis_tvalid),
        .s02_axis_tdata(s02_axis_tdata), .s02_axis_tready(dac_s_tready[1]), .s02_axis_tvalid(s02_axis_tvalid),
        .s10_axis_tdata(s10_axis_tdata), .s10_axis_tready(dac_s_tready[2]), .s10_axis_tvalid(s10_axis_tvalid),
        .s12_axis_tdata(s12_axis_tdata), .s12_axis_tready(dac_s_tready[3]), .s12_axis_tvalid(s12_axis_tvalid),
        .s20_axis_tdata(s20_axis_tdata), .s20_axis_tready(dac_s_tready[4]), .s20_axis_tvalid(s20_axis_tvalid),
        .s22_axis_tdata(s22_axis_tdata), .s22_axis_tready(dac_s_tready[5]), .s22_axis_tvalid(s22_axis_tvalid),
        .s30_axis_tdata(s30_axis_tdata), .s30_axis_tready(dac_s_tready[6]), .s30_axis_tvalid(s30_axis_tvalid),
        .s32_axis_tdata(s32_axis_tdata), .s32_axis_tready(dac_s_tready[7]), .s32_axis_tvalid(s32_axis_tvalid),
        .sysref_in_diff_n(sysref_in_n), .sysref_in_diff_p(sysref_in_p),
        .fclk_100m(fclk_100m), .up_rack(up_rack), .up_raddr(up_raddr),
        .up_rdata(up_rdata), .up_rreq(up_rreq), .up_wack(up_wack),
        .up_waddr(up_waddr), .up_wdata(up_wdata), .up_wreq(up_wreq),
        .adc_fabric_ref(pl_clk), .user_sysref_adc_0(user_sysref_adc),
        .user_sysref_dac_0(user_sysref_dac),
        .vin0_01_v_n(vin0_01_n), .vin0_01_v_p(vin0_01_p),
        .vin0_23_v_n(vin0_23_n), .vin0_23_v_p(vin0_23_p),
        .vin1_01_v_n(vin1_01_n), .vin1_01_v_p(vin1_01_p),
        .vin1_23_v_n(vin1_23_n), .vin1_23_v_p(vin1_23_p),
        .vin2_01_v_n(vin2_01_n), .vin2_01_v_p(vin2_01_p),
        .vin2_23_v_n(vin2_23_n), .vin2_23_v_p(vin2_23_p),
        .vin3_01_v_n(vin3_01_n), .vin3_01_v_p(vin3_01_p),
        .vin3_23_v_n(vin3_23_n), .vin3_23_v_p(vin3_23_p),
        .vout00_v_n(vout00_n), .vout00_v_p(vout00_p),
        .vout02_v_n(vout02_n), .vout02_v_p(vout02_p),
        .vout10_v_n(vout10_n), .vout10_v_p(vout10_p),
        .vout12_v_n(vout12_n), .vout12_v_p(vout12_p),
        .vout20_v_n(vout20_n), .vout20_v_p(vout20_p),
        .vout22_v_n(vout22_n), .vout22_v_p(vout22_p),
        .vout30_v_n(vout30_n), .vout30_v_p(vout30_p),
        .vout32_v_n(vout32_n), .vout32_v_p(vout32_p)
    );

    // Preserve observability of both boundary layers without ILA/JTAG.
    assign led[0] = dac_s_tdata[15] ^ dac_s_tvalid[0];
    assign led[1] = (^rx_probe_data) ^ rx_host_data[15] ^ adc_ch_valid[0];

endmodule


(* KEEP_HIERARCHY = "yes" *)
module d0_tx_stub #(
    parameter integer CHANNEL = 0
) (
    input  tx_clk, input dac_clk, input tx_resetn, input dac_resetn,
    output reg [255:0] dac_tdata,
    output reg dac_tvalid,
    input  dac_tready
);
    reg [11:0] rd_addr;
    reg [511:0] tx_pipe_stage0;
    reg [511:0] tx_pipe_stage1;
    wire [503:0] uram_rd;
    reg [3:0] half_select;

    // A real write port prevents ROM optimization and forces seven URAM288.
    xpm_memory_sdpram #(
        .MEMORY_SIZE(2064384), .MEMORY_PRIMITIVE("ultra"),
        .CLOCKING_MODE("common_clock"), .ECC_MODE("no_ecc"),
        .MEMORY_INIT_FILE("none"), .MEMORY_INIT_PARAM(""), .USE_MEM_INIT(0),
        .MEMORY_OPTIMIZATION("true"), .CASCADE_HEIGHT(0), .SIM_ASSERT_CHK(0),
        .WRITE_DATA_WIDTH_A(504), .BYTE_WRITE_WIDTH_A(504), .ADDR_WIDTH_A(12),
        .READ_DATA_WIDTH_B(504), .ADDR_WIDTH_B(12), .READ_LATENCY_B(3),
        .WRITE_MODE_B("read_first"), .RST_MODE_B("SYNC")
    ) uram_i (
        .sleep(1'b0), .clka(tx_clk), .ena(1'b1), .wea(1'b1),
        .addra(rd_addr), .dina({42{rd_addr}}),
        .injectdbiterra(1'b0), .injectsbiterra(1'b0),
        .clkb(tx_clk), .rstb(1'b0), .enb(1'b1), .regceb(1'b1),
        .addrb(rd_addr), .doutb(uram_rd)
    );

    always @(posedge tx_clk or negedge tx_resetn) begin
        if (!tx_resetn) begin
            rd_addr <= 12'd0;
        end else begin
            rd_addr <= rd_addr + 12'd1;
        end
    end

    // Unreset data stages keep the URAM output local and give placement
    // movable pipeline depth before the DAC boundary.
    always @(posedge tx_clk) begin
        tx_pipe_stage0 <= {8'd0, uram_rd};
        tx_pipe_stage1 <= tx_pipe_stage0;
    end

    always @(posedge dac_clk or negedge dac_resetn) begin
        if (!dac_resetn) begin
            half_select <= 4'b0000;
            dac_tvalid <= 1'b0;
        end else begin
            half_select <= ~half_select;
            dac_tvalid <= 1'b1;
        end
    end

    genvar half;
    generate
        for (half = 0; half < 4; half = half + 1) begin : g_dac_mux
            always @(posedge dac_clk) begin
                dac_tdata[half*64 +: 64] <= half_select[half]
                    ? tx_pipe_stage1[256 + half*64 +: 64]
                    : tx_pipe_stage1[half*64 +: 64];
            end
        end
    endgenerate

    wire unused_ready = dac_tready;
    wire unused_channel = CHANNEL[0];
endmodule


(* KEEP_HIERARCHY = "yes" *)
module d0_rx_stub #(
    parameter integer CHANNEL = 0
) (
    input  adc_clk, input rx_clk, input host_clk,
    input adc_resetn, input rx_resetn, input host_resetn,
    input  [191:0] adc_tdata,
    input  adc_tvalid,
    output reg [31:0] host_data,
    output reg [335:0] probe_data
);
    reg [191:0] adc_stage;
    reg [191:0] adc_prev;
    reg [383:0] adc_pair_stage;
    reg adc_stage_valid;
    reg adc_prev_valid;
    reg adc_pair_valid;
    reg [335:0] packed_next;
    reg [335:0] packed_stage;
    reg packed_valid;
    reg [11:0] wr_addr;
    reg [11:0] host_addr;
    wire [335:0] rx_bram_read;
    integer j;

    // RFDC boundary stage: no reset and one fanout level, into the pair stage.
    always @(posedge adc_clk) begin
        adc_stage <= adc_tdata;
        adc_prev <= adc_stage;
        adc_pair_stage[191:0] <= adc_prev;
        adc_pair_stage[383:192] <= adc_stage;
    end

    always @(posedge adc_clk or negedge adc_resetn) begin
        if (!adc_resetn) begin
            adc_stage_valid <= 1'b0;
            adc_prev_valid <= 1'b0;
            adc_pair_valid <= 1'b0;
        end else begin
            adc_stage_valid <= adc_tvalid;
            adc_prev_valid <= adc_stage_valid;
            adc_pair_valid <= adc_stage_valid && adc_prev_valid;
        end
    end

    // Pairing and 14-bit packing begin after the RFDC input register.
    always @* begin
        packed_next = 336'd0;
        for (j = 0; j < 12; j = j + 1) begin
            packed_next[j*14 +: 14] = adc_pair_stage[j*16 + 2 +: 14];
            packed_next[(j+12)*14 +: 14] = adc_pair_stage[192 + j*16 + 2 +: 14];
        end
    end

    always @(posedge rx_clk) begin
        packed_stage <= packed_next;
    end

    always @(posedge rx_clk or negedge rx_resetn) begin
        if (!rx_resetn) packed_valid <= 1'b0;
        else packed_valid <= adc_pair_valid;
    end

    always @(posedge rx_clk or negedge rx_resetn) begin
        if (!rx_resetn) begin
            wr_addr <= 12'd0;
        end else if (packed_valid) begin
            if (wr_addr == 12'd2729) wr_addr <= 12'd0;
            else wr_addr <= wr_addr + 12'd1;
        end
    end

    always @(posedge host_clk or negedge host_resetn) begin
        if (!host_resetn) begin
            host_addr <= 12'd0;
        end else begin
            if (host_addr == 12'd2729) host_addr <= 12'd0;
            else host_addr <= host_addr + 12'd1;
        end
    end

    always @(posedge host_clk) begin
        host_data <= rx_bram_read[31:0];
        probe_data <= rx_bram_read;
    end

    genvar bank;
    generate
        for (bank = 0; bank < 5; bank = bank + 1) begin : g_bram_bank
            localparam integer BANK_WIDTH = (bank < 4) ? 72 : 48;
            (* DONT_TOUCH = "TRUE", MAX_FANOUT = 8 *) reg [11:0] wr_addr_bank;
            (* DONT_TOUCH = "TRUE", MAX_FANOUT = 8 *) reg wr_enable_bank;
            reg [BANK_WIDTH-1:0] wr_data_bank;
            (* DONT_TOUCH = "TRUE", MAX_FANOUT = 8 *) reg [11:0] host_addr_bank;
            wire [BANK_WIDTH-1:0] rd_data_bank;

            always @(posedge rx_clk or negedge rx_resetn) begin
                if (!rx_resetn) begin
                    wr_addr_bank <= 12'd0;
                    wr_enable_bank <= 1'b0;
                end else begin
                    wr_addr_bank <= wr_addr;
                    wr_enable_bank <= packed_valid;
                end
            end

            always @(posedge rx_clk) begin
                wr_data_bank <= packed_stage[bank*72 +: BANK_WIDTH];
            end

            always @(posedge host_clk or negedge host_resetn) begin
                if (!host_resetn) host_addr_bank <= 12'd0;
                else host_addr_bank <= host_addr;
            end

            xpm_memory_sdpram #(
                .MEMORY_SIZE(BANK_WIDTH*2730), .MEMORY_PRIMITIVE("block"),
                .CLOCKING_MODE("independent_clock"), .ECC_MODE("no_ecc"),
                .MEMORY_INIT_FILE("none"), .MEMORY_INIT_PARAM(""), .USE_MEM_INIT(0),
                .MEMORY_OPTIMIZATION("true"), .CASCADE_HEIGHT(0), .SIM_ASSERT_CHK(0),
                .WRITE_DATA_WIDTH_A(BANK_WIDTH), .BYTE_WRITE_WIDTH_A(BANK_WIDTH), .ADDR_WIDTH_A(12),
                .READ_DATA_WIDTH_B(BANK_WIDTH), .ADDR_WIDTH_B(12), .READ_LATENCY_B(2),
                .WRITE_MODE_B("read_first"), .RST_MODE_B("SYNC")
            ) rx_bram_i (
                .sleep(1'b0), .clka(rx_clk), .ena(wr_enable_bank), .wea(wr_enable_bank),
                .addra(wr_addr_bank), .dina(wr_data_bank),
                .injectdbiterra(1'b0), .injectsbiterra(1'b0),
                .clkb(host_clk), .rstb(1'b0), .enb(host_resetn), .regceb(host_resetn),
                .addrb(host_addr_bank), .doutb(rd_data_bank)
            );

            assign rx_bram_read[bank*72 +: BANK_WIDTH] = rd_data_bank;
        end
    endgenerate

    wire unused_channel = CHANNEL[0];
endmodule


module d0_reset_sync (
    input clk,
    input async_resetn,
    output resetn
);
    (* ASYNC_REG = "TRUE", SHREG_EXTRACT = "NO" *) reg [1:0] reset_sync;

    always @(posedge clk or negedge async_resetn) begin
        if (!async_resetn) reset_sync <= 2'b00;
        else reset_sync <= {reset_sync[0], 1'b1};
    end

    assign resetn = reset_sync[1];
endmodule
